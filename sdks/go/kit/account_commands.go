// proven is the open token of purpose that value proves: its ID, or why not.
func proven(s Account, purpose TokenPurpose, value, aggregateID string, now int64) (string, error) {
	invalid := rejected("The link is not valid", "invalid_token")
	account, tokenID, secret, ok := ParseToken(value)
	if !ok {
		return "", invalid
	}
	i := slices.IndexFunc(s.OpenTokens, func(t OpenToken) bool { return t.Purpose == purpose && t.TokenID == tokenID })
	if i < 0 {
		return "", invalid
	}
	open := s.OpenTokens[i]
	if account != aggregateID || open.Token == nil || !EqualSecrets(*open.Token, secret) {
		return "", invalid
	}
	if now > open.ExpiresAt {
		return "", rejected("The link has expired", "expired_token")
	}
	return open.TokenID, nil
}

