func gone(s Account) bool { return s.Status == AccountStatusNone || s.Status == AccountStatusDeleted }

func activeAccount(s Account) error {
	if s.Status == AccountStatusActive {
		return nil
	}
	return rejected("The account is not active", "invalid_state")
}

func deref(s *string) string {
	if s == nil {
		return ""
	}
	return *s
}

