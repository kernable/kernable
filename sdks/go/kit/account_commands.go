// anotherMethod is whether the account keeps another way to sign in (never remove the last one).
func anotherMethod(s Account, passkey *string, linkProvider, linkSubject *string) bool {
	if s.Password != nil {
		return true
	}
	for _, p := range s.Passkeys {
		if !eqPtr(p.CredentialID, passkey) {
			return true
		}
	}
	for _, x := range s.Links {
		if linkProvider == nil || !(x.Provider == *linkProvider && x.Subject != nil && *x.Subject == *linkSubject) {
			return true
		}
	}
	return false
}

// asserted is the passkey a sign-in answer proves, with its new counter.
func asserted(s Account, challenge string, response map[string]any) *PasskeyUsed {
	id, ok := response["id"].(string)
	if !ok {
		return nil
	}
	i := slices.IndexFunc(s.Passkeys, func(p Passkey) bool { return p.CredentialID != nil && *p.CredentialID == id })
	if i < 0 {
		return nil
	}
	p := s.Passkeys[i]
	counter, err := VerifyAuthentication(response, challenge, p.PublicKey, p.Counter)
	if err != nil {
		return nil
	}
	return &PasskeyUsed{CredentialID: p.CredentialID, Counter: counter}
}

