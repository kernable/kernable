func recoveryHashes(codes []string) ([]string, error) {
	if len(codes) < 8 || slices.ContainsFunc(codes, func(c string) bool { return utf8.RuneCountInString(c) < 10 }) {
		return nil, rejected("At least 8 recovery codes of 10 characters", "invalid_recovery_codes")
	}
	out := make([]string, len(codes))
	for i, c := range codes {
		out[i] = SHA256(c)
	}
	return out, nil
}

type proof struct {
	method           SecondFactor
	step             *int64
	recoveryCodeHash *string
}

// secondFactor is what a TOTP code (once) or an unused recovery code proves.
func secondFactor(s Account, code string, now int64) *proof {
	if s.Totp == nil || !s.Totp.Confirmed || s.Totp.Secret == nil {
		return nil
	}
	if step, ok := TOTPStep(*s.Totp.Secret, code, now); ok {
		if step > s.Totp.LastStep {
			return &proof{method: FactorTotp, step: &step}
		}
		return nil
	}
	digest := SHA256(code)
	if slices.Contains(s.RecoveryCodes, digest) {
		return &proof{method: FactorRecovery, recoveryCodeHash: &digest}
	}
	return nil
}

