// --- Signing in ---------------------------------------------------------------------------

func refreshOK(refreshToken, sessionID string) error {
	session, generation, _, ok := ParseToken(refreshToken)
	if ok && session == sessionID && generation == "1" {
		return nil
	}
	return rejected("A malformed refresh token", "invalid_token")
}

