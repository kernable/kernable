func nameChars(s string) bool {
	for _, c := range s {
		if !(c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' || c >= '0' && c <= '9' || c == '_' || c == '-') {
			return false
		}
	}
	return true
}

func providerName(value string) (string, error) {
	var ok bool
	if id, sso := strings.CutPrefix(value, "sso:"); sso {
		ok = id != "" && nameChars(id)
	} else {
		ok = len(value) >= 2 && len(value) <= 41 && value[0] >= 'a' && value[0] <= 'z' && nameChars(value)
	}
	if !ok {
		return "", rejected("A provider is a name, or sso:<id>", "invalid_provider")
	}
	return value, nil
}

