// issuerURL is an issuer URL without its trailing slashes: https:// and a host, no space
// characters. Plain http:// only for localhost and 127.0.0.1 (development and tests).
func issuerURL(value string) (string, error) {
	v := ""
	if !HasSpace(value) {
		v = strings.TrimRight(value, "/")
	}
	secure := false
	if r, ok := strings.CutPrefix(v, "https://"); ok {
		secure = r != "" && !strings.HasPrefix(r, "/")
	}
	local := false
	if r, ok := strings.CutPrefix(v, "http://"); ok {
		rest, host := strings.CutPrefix(r, "localhost")
		if !host {
			rest, host = strings.CutPrefix(r, "127.0.0.1")
		}
		if host {
			local = true
			if p, port := strings.CutPrefix(rest, ":"); port {
				digits := 0
				for digits < len(p) && p[digits] >= '0' && p[digits] <= '9' {
					digits++
				}
				if digits == 0 {
					local = false
				}
				rest = p[digits:]
			}
			local = local && (rest == "" || strings.HasPrefix(rest, "/"))
		}
	}
	if secure || local {
		return v, nil
	}
	return "", rejected("An https:// issuer URL", "invalid_issuer")
}

func ssoDomainName(value string) (string, error) {
	d := strings.ToLower(TrimSpace(value))
	labels := strings.Split(d, ".")
	ok := len(labels) >= 2
	for _, l := range labels {
		valid := l != "" && !strings.HasPrefix(l, "-") && !strings.HasSuffix(l, "-") && !strings.Contains(l, "--")
		for i := 0; valid && i < len(l); i++ {
			c := l[i]
			valid = c >= 'a' && c <= 'z' || c >= '0' && c <= '9' || c == '-'
		}
		ok = ok && valid
	}
	tld := labels[len(labels)-1]
	tldOK := len(tld) >= 2
	for i := 0; tldOK && i < len(tld); i++ {
		tldOK = tld[i] >= 'a' && tld[i] <= 'z'
	}
	if ok && tldOK {
		return d, nil
	}
	return "", rejected("A domain name", "invalid_domain")
}

