type Events = Result<Vec<NewEvent>, Rejected>;

fn rejected(message: &str, code: &str) -> Rejected {
    Rejected::new(message).code(code)
}

fn gone(s: &Account) -> bool {
    matches!(s.status, AccountStatus::None | AccountStatus::Deleted)
}

fn active(s: &Account) -> Result<(), Rejected> {
    if s.status == AccountStatus::Active {
        Ok(())
    } else {
        Err(rejected("The account is not active", "invalid_state"))
    }
}

