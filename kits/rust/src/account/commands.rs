/// A new verification token, kept in the vault under its own subject until used.
fn verification_requested(email: Option<String>, at: i64) -> NewEvent {
    VerificationRequested {
        token_id: random_secret(9),
        token: Some(random_secret(32)),
        email,
        expires_at: at + VERIFICATION_HOURS * HOUR,
    }
    .into()
}

