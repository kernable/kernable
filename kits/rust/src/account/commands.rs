fn recovery_hashes(codes: &[String]) -> Result<Vec<String>, Rejected> {
    if codes.len() < 8 || codes.iter().any(|c| c.chars().count() < 10) {
        return Err(rejected(
            "At least 8 recovery codes of 10 characters",
            "invalid_recovery_codes",
        ));
    }
    Ok(codes.iter().map(|c| sha256(c)).collect())
}

/// What a TOTP code (once) or an unused recovery code proves.
struct Proof {
    method: SecondFactor,
    step: Option<i64>,
    recovery_code_hash: Option<String>,
}

fn second_factor(s: &Account, code: &str, now: i64) -> Option<Proof> {
    let totp = s.totp.as_ref().filter(|t| t.confirmed)?;
    let secret = totp.secret.as_deref()?;
    if let Some(step) = totp_step(secret, code, now) {
        return (step > totp.last_step).then_some(Proof {
            method: SecondFactor::Totp,
            step: Some(step),
            recovery_code_hash: None,
        });
    }
    let digest = sha256(code);
    s.recovery_codes.contains(&digest).then_some(Proof {
        method: SecondFactor::Recovery,
        step: None,
        recovery_code_hash: Some(digest),
    })
}

