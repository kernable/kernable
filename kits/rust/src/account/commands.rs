fn issuer(value: &str) -> Result<String, Rejected> {
    let rest = value
        .strip_prefix("https://")
        .or_else(|| value.strip_prefix("http://"));
    match rest {
        Some(r) if !r.is_empty() && !value.contains(char::is_whitespace) => {
            Ok(value.trim_end_matches('/').to_owned())
        }
        _ => Err(rejected("An issuer URL", "invalid_issuer")),
    }
}

fn sso_domain(value: &str) -> Result<String, Rejected> {
    let d = value.trim().to_lowercase();
    let labels: Vec<&str> = d.split('.').collect();
    let label_ok = |l: &&str| {
        !l.is_empty()
            && l.bytes()
                .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == b'-')
            && !l.starts_with('-')
            && !l.ends_with('-')
            && !l.contains("--")
    };
    let tld_ok = labels
        .last()
        .is_some_and(|t| t.len() >= 2 && t.bytes().all(|c| c.is_ascii_lowercase()));
    if labels.len() >= 2 && labels.iter().all(label_ok) && tld_ok {
        Ok(d)
    } else {
        Err(rejected("A domain name", "invalid_domain"))
    }
}

