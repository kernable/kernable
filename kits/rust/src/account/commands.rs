// --- Signing in -------------------------------------------------------------------------------------------

fn refresh_ok(refresh_token: &str, session_id: &str) -> Result<(), Rejected> {
    match parse_token(refresh_token) {
        Some((session, generation, _)) if session == session_id && generation == "1" => Ok(()),
        _ => Err(rejected("A malformed refresh token", "invalid_token")),
    }
}

