/// The open token of `purpose` that `value` proves: its ID, or why not.
fn proven(
    s: &Account,
    purpose: TokenPurpose,
    value: &str,
    aggregate_id: &str,
    now: i64,
) -> Result<String, Rejected> {
    let invalid = || rejected("The link is not valid", "invalid_token");
    let (account, token_id, secret) = parse_token(value).ok_or_else(invalid)?;
    let open = s
        .open_tokens
        .iter()
        .find(|t| t.purpose == purpose && t.token_id == token_id)
        .ok_or_else(invalid)?;
    if account != aggregate_id
        || !open
            .token
            .as_deref()
            .is_some_and(|t| equal_secrets(t, &secret))
    {
        return Err(invalid());
    }
    if now > open.expires_at {
        return Err(rejected("The link has expired", "expired_token"));
    }
    Ok(open.token_id.clone())
}

