fn provider(value: &str) -> Result<String, Rejected> {
    let name_char = |c: char| c.is_ascii_alphanumeric() || c == '_' || c == '-';
    let ok = match value.strip_prefix("sso:") {
        Some(id) => !id.is_empty() && id.chars().all(name_char),
        None => {
            (2..=41).contains(&value.len())
                && value.starts_with(|c: char| c.is_ascii_lowercase())
                && value.chars().all(name_char)
        }
    };
    if ok {
        Ok(value.to_owned())
    } else {
        Err(rejected(
            "A provider is a name, or sso:<id>",
            "invalid_provider",
        ))
    }
}

