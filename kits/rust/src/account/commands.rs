/// Whether the account keeps another way to sign in (never remove the last one).
fn another_method(s: &Account, passkey: Option<&str>, link: Option<(&str, &str)>) -> bool {
    s.password.is_some()
        || s.passkeys
            .iter()
            .any(|p| p.credential_id.as_deref() != passkey)
        || s.links.iter().any(|x| {
            link.is_none_or(|(p, sub)| !(x.provider == p && x.subject.as_deref() == Some(sub)))
        })
}

/// The passkey a sign-in answer proves, with its new counter.
fn asserted(s: &Account, challenge: &str, response: &Value) -> Option<PasskeyUsed> {
    let id = response["id"].as_str()?;
    let passkey = s
        .passkeys
        .iter()
        .find(|p| p.credential_id.as_deref() == Some(id))?;
    let counter =
        passkeys::verify_authentication(response, challenge, &passkey.public_key, passkey.counter)
            .ok()?;
    Some(PasskeyUsed {
        credential_id: passkey.credential_id.clone(),
        counter,
    })
}

