pub fn handle(account: &Aggregate<Account>, session: &Aggregate<Session>, sso: &Aggregate<Sso>) {
    account.command(RegisterAccount, |s, d, _, ctx| {
        let at = ctx.now().millis();
        // A registration whose verification expired unverified is taken over by a new one of the same address.
        let expired = s.status == AccountStatus::Pending
            && !s
                .open_tokens
                .iter()
                .any(|t| t.purpose == TokenPurpose::Verify && t.expires_at > at);
        if s.status != AccountStatus::None && !expired {
            return Err(rejected("The account exists", "exists"));
        }
        let email = normal_email(&d.email);
        if expired && Some(&email) != s.email.as_ref() {
            return Err(rejected(
                "Only the same address takes over a registration",
                "exists",
            ));
        }
        if !valid_email(&email) {
            return Err(rejected("Not an email address", "invalid_email"));
        }
        if d.name.trim().is_empty() || d.name.chars().count() > 200 {
            return Err(rejected("A name is needed", "invalid_name"));
        }
        if d.password.as_deref().is_some_and(|p| !valid_password(p)) {
            return Err(rejected(
                "A password has 10 to 1024 characters",
                "weak_password",
            ));
        }
        let verified = d.verified == Some(true);
        let registered = AccountRegistered {
            email: Some(email.clone()),
            name: Some(d.name.trim().to_owned()),
            password_hash: d.password.as_deref().map(hash_password),
            verified,
            at,
        };
        Ok(if verified {
            vec![registered.into()]
        } else {
            vec![registered.into(), verification_requested(Some(email), at)]
        })
    });

    account.command(RequestVerification, |s, _, _, ctx| {
        if s.status != AccountStatus::Pending {
            return Err(rejected(
                "Only a pending account is verified",
                "invalid_state",
            ));
        }
        Ok(vec![verification_requested(
            s.email.clone(),
            ctx.now().millis(),
        )])
    });

    account.command(VerifyEmail, |s, d, cmd, ctx| {
        Ok(vec![
            EmailVerified {
                token_id: proven(
                    s,
                    TokenPurpose::Verify,
                    &d.token,
                    &cmd.aggregate_id,
                    ctx.now().millis(),
                )?,
            }
            .into(),
        ])
    });

    account.command(SignIn, |s, d, _, ctx| {
        let at = ctx.now().millis();
        if gone(s) {
            return Err(rejected("No such account", "not_found"));
        }
        refresh_ok(&d.refresh_token, &d.session_id)?;
        if at < s.locked_until() {
            return failed("password", FailureReason::Locked, d.ip, at);
        }
        if !check_password(
            s.password.as_ref().and_then(|p| p.hash.as_deref()),
            &d.password,
        ) {
            return failed("password", FailureReason::WrongPassword, d.ip, at);
        }
        match s.status {
            AccountStatus::Pending => {
                return failed("password", FailureReason::NotVerified, d.ip, at);
            }
            AccountStatus::Active => {}
            _ => return failed("password", FailureReason::NotActive, d.ip, at),
        }
        Ok(vec![
            SignedIn {
                session_id: d.session_id,
                method: "password".into(),
                factors: vec!["password".into()],
                refresh_token_hash: sha256(&d.refresh_token),
                ip: d.ip,
                user_agent: d.user_agent,
                mfa: s.mfa(),
                at,
            }
            .into(),
        ])
    });

    session.command(OpenSession, |s, d, _, _| {
        if s.status != SessionStatus::None {
            return Err(rejected("The session exists", "exists"));
        }
        Ok(vec![
            SessionOpened {
                account_id: d.account_id,
                method: d.method,
                factors: d.factors,
                refresh_token_hash: d.refresh_token_hash,
                ip: d.ip,
                user_agent: d.user_agent,
                at: d.at,
            }
            .into(),
        ])
    });

    session.command(RefreshSession, |s, d, cmd, ctx| {
        let at = ctx.now().millis();
        let invalid = || rejected("Not a valid session", "invalid_token");
        let parts = parse_token(&d.refresh_token).filter(|p| p.0 == cmd.aggregate_id);
        let Some((_, generation, _)) = parts.filter(|_| s.status == SessionStatus::Active) else {
            return Err(invalid());
        };
        let generation: i64 = generation.parse().unwrap_or(-1);
        let current = s.generation as i64;
        if generation < current {
            return Ok(vec![
                SessionEnded {
                    reason: SessionEnd::Reuse,
                }
                .into(),
            ]);
        }
        if generation != current || sha256(&d.refresh_token) != s.refresh_token_hash {
            return Err(invalid());
        }
        if at > s.last_refresh_at + SESSION_IDLE_DAYS * DAY {
            return Ok(vec![
                SessionEnded {
                    reason: SessionEnd::Idle,
                }
                .into(),
            ]);
        }
        if at > s.opened_at + SESSION_MAX_DAYS * DAY {
            return Ok(vec![
                SessionEnded {
                    reason: SessionEnd::Expired,
                }
                .into(),
            ]);
        }
        let next = parse_token(&d.new_refresh_token);
        if !next.is_some_and(|n| n.0 == cmd.aggregate_id && n.1 == (s.generation + 1).to_string()) {
            return Err(rejected("A malformed refresh token", "invalid_token"));
        }
        Ok(vec![
            SessionRefreshed {
                generation: s.generation + 1,
                refresh_token_hash: sha256(&d.new_refresh_token),
                ip: d.ip,
                account_id: s.account_id.clone(),
                factors: s.factors.clone(),
                at,
            }
            .into(),
        ])
    });

    session.command(AddSessionFactor, |s, d, _, _| {
        if s.status != SessionStatus::Active {
            return Err(rejected("The session has ended", "invalid_state"));
        }
        if d.account_id != s.account_id {
            return Err(rejected("Another account's session", "invalid_session"));
        }
        Ok(if s.factors.contains(&d.factor) {
            vec![]
        } else {
            vec![SessionFactorAdded { factor: d.factor }.into()]
        })
    });

    session.command(EndSession, |s, d, _, _| {
        if s.status != SessionStatus::Active {
            return Err(rejected("The session has ended", "invalid_state"));
        }
        Ok(vec![
            SessionEnded {
                reason: d.reason.unwrap_or(SessionEnd::SignedOut),
            }
            .into(),
        ])
    });

    account.command(SuspendAccount, |s, d, _, ctx| {
        if !matches!(s.status, AccountStatus::Pending | AccountStatus::Active) {
            return Err(rejected("Cannot suspend this account", "invalid_state"));
        }
        Ok(vec![
            AccountSuspended {
                reason: d.reason,
                at: ctx.now().millis(),
            }
            .into(),
        ])
    });

    account.command(ReactivateAccount, |s, _, _, _| {
        if s.status != AccountStatus::Suspended {
            return Err(rejected(
                "Only a suspended account is reactivated",
                "invalid_state",
            ));
        }
        Ok(vec![AccountReactivated {}.into()])
    });

    account.command(DeleteAccount, |s, _, _, _| {
        if s.status != AccountStatus::Suspended {
            return Err(rejected(
                "Only a suspended account is deleted",
                "invalid_state",
            ));
        }
        Ok(vec![AccountDeleted {}.into()])
    });

    account.command(ChangePassword, |s, d, _, ctx| {
        active(s)?;
        if let Some(password) = &s.password
            && !check_password(
                password.hash.as_deref(),
                d.current.as_deref().unwrap_or_default(),
            )
        {
            return Err(rejected("The current password is wrong", "wrong_password"));
        }
        if !valid_password(&d.new) {
            return Err(rejected(
                "A password has 10 to 1024 characters",
                "weak_password",
            ));
        }
        Ok(vec![
            PasswordChanged {
                hash: Some(hash_password(&d.new)),
                keep_session_id: d.keep_session_id,
                at: ctx.now().millis(),
            }
            .into(),
        ])
    });

    account.command(RequestPasswordReset, |s, _, _, ctx| {
        active(s)?;
        Ok(vec![
            PasswordResetRequested {
                token_id: random_secret(9),
                token: Some(random_secret(32)),
                email: s.email.clone(),
                expires_at: ctx.now().millis() + RESET_MINUTES * MINUTE,
            }
            .into(),
        ])
    });

    account.command(ResetPassword, |s, d, cmd, ctx| {
        let token_id = proven(
            s,
            TokenPurpose::Reset,
            &d.token,
            &cmd.aggregate_id,
            ctx.now().millis(),
        )?;
        if !valid_password(&d.new) {
            return Err(rejected(
                "A password has 10 to 1024 characters",
                "weak_password",
            ));
        }
        Ok(vec![
            PasswordReset {
                token_id,
                hash: Some(hash_password(&d.new)),
                at: ctx.now().millis(),
            }
            .into(),
        ])
    });

    account.command(RequestEmailChange, |s, d, _, ctx| {
        active(s)?;
        let email = normal_email(&d.email);
        if !valid_email(&email) {
            return Err(rejected("Not an email address", "invalid_email"));
        }
        if Some(&email) == s.email.as_ref() {
            return Err(rejected("That is the address already", "unchanged"));
        }
        Ok(vec![
            EmailChangeRequested {
                token_id: random_secret(9),
                token: Some(random_secret(32)),
                email: Some(email),
                expires_at: ctx.now().millis() + VERIFICATION_HOURS * HOUR,
            }
            .into(),
        ])
    });

    account.command(ConfirmEmailChange, |s, d, cmd, ctx| {
        let token_id = proven(
            s,
            TokenPurpose::EmailChange,
            &d.token,
            &cmd.aggregate_id,
            ctx.now().millis(),
        )?;
        Ok(vec![
            EmailChanged {
                token_id,
                email: s.pending_email.clone(),
            }
            .into(),
        ])
    });

    account.command(NoteRegistrationAttempt, |s, _, _, ctx| {
        if !matches!(s.status, AccountStatus::Active | AccountStatus::Suspended) {
            return Err(rejected("No account to tell", "invalid_state"));
        }
        Ok(vec![
            RegistrationAttempted {
                email: s.email.clone(),
                at: ctx.now().millis(),
            }
            .into(),
        ])
    });

    account.command(StartTotp, |s, d, _, _| {
        active(s)?;
        if s.mfa() {
            return Err(rejected("TOTP is on already", "exists"));
        }
        let base32 = (16..=64).contains(&d.secret.len())
            && d.secret
                .bytes()
                .all(|c| c.is_ascii_uppercase() || (b'2'..=b'7').contains(&c));
        if !base32 {
            return Err(rejected("A base32 secret", "invalid_secret"));
        }
        Ok(vec![
            TotpStarted {
                secret: Some(d.secret),
            }
            .into(),
        ])
    });

    account.command(ConfirmTotp, |s, d, _, ctx| {
        let Some(secret) = s
            .totp
            .as_ref()
            .filter(|t| !t.confirmed)
            .and_then(|t| t.secret.as_deref())
        else {
            return Err(rejected("Start TOTP first", "invalid_state"));
        };
        let now = ctx.now().millis();
        let step = totp_step(secret, &d.code, now)
            .ok_or_else(|| rejected("The code is not right", "wrong_code"))?;
        Ok(vec![
            TotpConfirmed { step, at: now }.into(),
            RecoveryCodesGenerated {
                hashes: recovery_hashes(&d.recovery_codes)?,
            }
            .into(),
        ])
    });

    account.command(DisableTotp, |s, d, _, ctx| {
        second_factor(s, &d.code, ctx.now().millis())
            .ok_or_else(|| rejected("The code is not right", "wrong_code"))?;
        Ok(vec![TotpDisabled {}.into()])
    });

    account.command(RegenerateRecoveryCodes, |s, d, _, ctx| {
        second_factor(s, &d.code, ctx.now().millis())
            .ok_or_else(|| rejected("The code is not right", "wrong_code"))?;
        Ok(vec![
            RecoveryCodesGenerated {
                hashes: recovery_hashes(&d.recovery_codes)?,
            }
            .into(),
        ])
    });

    account.command(ProveSecondFactor, |s, d, _, ctx| {
        let now = ctx.now().millis();
        if s.status != AccountStatus::Active || !s.mfa() {
            return Err(rejected("No second factor to prove", "invalid_state"));
        }
        let proof = if now < s.locked_until() {
            None
        } else {
            second_factor(s, &d.code, now)
        };
        Ok(vec![match proof {
            None => SecondFactorFailed {
                session_id: d.session_id,
                at: now,
            }
            .into(),
            Some(p) => SecondFactorProved {
                session_id: d.session_id,
                method: p.method,
                step: p.step,
                recovery_code_hash: p.recovery_code_hash,
            }
            .into(),
        }])
    });

    account.command(AddPasskey, |s, d, _, ctx| {
        active(s)?;
        let registered = passkeys::verify_registration(&d.response, &d.challenge)
            .map_err(|e| rejected(&format!("Not a valid passkey: {e}"), "invalid_passkey"))?;
        if s.passkeys
            .iter()
            .any(|p| p.credential_id.as_deref() == Some(&registered.credential_id))
        {
            return Err(rejected("The passkey is added already", "exists"));
        }
        Ok(vec![
            PasskeyAdded {
                credential_id: Some(registered.credential_id),
                public_key: registered.public_key,
                counter: registered.counter,
                label: d.label,
                at: ctx.now().millis(),
            }
            .into(),
        ])
    });

    account.command(RemovePasskey, |s, d, _, _| {
        if !s
            .passkeys
            .iter()
            .any(|p| p.credential_id.as_deref() == Some(&d.credential_id))
        {
            return Err(rejected("No such passkey", "not_found"));
        }
        if !another_method(s, Some(&d.credential_id), None) {
            return Err(rejected("The last way to sign in stays", "last_method"));
        }
        Ok(vec![
            PasskeyRemoved {
                credential_id: Some(d.credential_id),
            }
            .into(),
        ])
    });

    account.command(SignInWithPasskey, |s, d, _, ctx| {
        let at = ctx.now().millis();
        if gone(s) {
            return Err(rejected("No such account", "not_found"));
        }
        refresh_ok(&d.refresh_token, &d.session_id)?;
        if at < s.locked_until() {
            return failed("passkey", FailureReason::Locked, d.ip, at);
        }
        let Some(used) = asserted(s, &d.challenge, &d.response) else {
            return failed("passkey", FailureReason::WrongPassword, d.ip, at);
        };
        if s.status != AccountStatus::Active {
            return failed("passkey", FailureReason::NotActive, d.ip, at);
        }
        Ok(vec![
            used.into(),
            SignedIn {
                session_id: d.session_id,
                method: "passkey".into(),
                factors: vec!["passkey".into()],
                refresh_token_hash: sha256(&d.refresh_token),
                ip: d.ip,
                user_agent: d.user_agent,
                mfa: false,
                at,
            }
            .into(),
        ])
    });

    account.command(ProvePasskey, |s, d, _, ctx| {
        active(s)?;
        Ok(match asserted(s, &d.challenge, &d.response) {
            None => vec![
                SecondFactorFailed {
                    session_id: d.session_id,
                    at: ctx.now().millis(),
                }
                .into(),
            ],
            Some(used) => vec![
                used.into(),
                SecondFactorProved {
                    session_id: d.session_id,
                    method: SecondFactor::Passkey,
                    step: None,
                    recovery_code_hash: None,
                }
                .into(),
            ],
        })
    });

    account.command(SignInWithProvider, |s, d, _, ctx| {
        let at = ctx.now().millis();
        let p = provider(&d.provider)?;
        if gone(s) {
            return Err(rejected("No such account", "not_found"));
        }
        refresh_ok(&d.refresh_token, &d.session_id)?;
        if d.subject.is_empty() {
            return Err(rejected("Which subject?", "invalid_subject"));
        }
        if s.status != AccountStatus::Active {
            return failed(&p, FailureReason::NotActive, d.ip, at);
        }
        let email = normal_email(d.email.as_deref().unwrap_or_default());
        let linked = s
            .links
            .iter()
            .any(|x| x.provider == p && x.subject.as_deref() == Some(&d.subject));
        let auto = !linked
            && d.auto_link == Some(true)
            && d.email_verified == Some(true)
            && s.email.as_deref() == Some(email.as_str());
        if !linked && !auto {
            return failed(&p, FailureReason::NotLinked, d.ip, at);
        }
        let signed = SignedIn {
            session_id: d.session_id,
            factors: vec![
                if p.starts_with("sso:") {
                    "sso"
                } else {
                    "provider"
                }
                .into(),
            ],
            method: p.clone(),
            refresh_token_hash: sha256(&d.refresh_token),
            ip: d.ip,
            user_agent: d.user_agent,
            mfa: s.mfa(),
            at,
        };
        Ok(if auto {
            vec![
                ProviderLinked {
                    provider: p,
                    subject: Some(d.subject),
                    email: Some(email),
                    at,
                }
                .into(),
                signed.into(),
            ]
        } else {
            vec![signed.into()]
        })
    });

    account.command(LinkProvider, |s, d, _, ctx| {
        active(s)?;
        let p = provider(&d.provider)?;
        if d.subject.is_empty() {
            return Err(rejected("Which subject?", "invalid_subject"));
        }
        if s.links
            .iter()
            .any(|x| x.provider == p && x.subject.as_deref() == Some(&d.subject))
        {
            return Err(rejected("Linked already", "exists"));
        }
        let email = d.email.filter(|e| !e.is_empty()).map(|e| normal_email(&e));
        Ok(vec![
            ProviderLinked {
                provider: p,
                subject: Some(d.subject),
                email,
                at: ctx.now().millis(),
            }
            .into(),
        ])
    });

    account.command(UnlinkProvider, |s, d, _, _| {
        if !s
            .links
            .iter()
            .any(|x| x.provider == d.provider && x.subject.as_deref() == Some(&d.subject))
        {
            return Err(rejected("Not linked", "not_found"));
        }
        if !another_method(s, None, Some((&d.provider, &d.subject))) {
            return Err(rejected("The last way to sign in stays", "last_method"));
        }
        Ok(vec![
            ProviderUnlinked {
                provider: d.provider,
                subject: Some(d.subject),
            }
            .into(),
        ])
    });

    sso.command(CreateSso, |s, d, _, _| {
        if s.status != SsoStatus::None {
            return Err(rejected("The SSO exists", "exists"));
        }
        if d.client_id.is_empty() || d.client_secret.is_empty() {
            return Err(rejected("A client ID and secret", "invalid_client"));
        }
        Ok(vec![
            SsoCreated {
                issuer: issuer(&d.issuer)?,
                client_id: d.client_id,
                client_secret: Some(d.client_secret),
            }
            .into(),
        ])
    });

    sso.command(UpdateSso, |s, d, _, _| {
        sso_exists(s)?;
        Ok(vec![
            SsoUpdated {
                issuer: issuer(&d.issuer)?,
                client_id: d.client_id,
                client_secret: Some(d.client_secret),
            }
            .into(),
        ])
    });

    sso.command(AddSsoDomain, |s, d, _, _| {
        sso_exists(s)?;
        let domain = sso_domain(&d.domain)?;
        if s.domains.iter().any(|x| x.domain == domain) {
            return Err(rejected("Added already", "exists"));
        }
        Ok(vec![
            SsoDomainAdded {
                domain,
                txt: format!("kernable-sso={}", random_secret(18)),
            }
            .into(),
        ])
    });

    sso.command(VerifySsoDomain, |s, d, _, _| {
        let x = s
            .domains
            .iter()
            .find(|y| y.domain == d.domain)
            .ok_or_else(|| rejected("No such domain", "not_found"))?;
        if x.verified {
            return Ok(vec![]);
        }
        if !d.found.contains(&x.txt) {
            return Err(rejected("The TXT record is not there", "not_verified"));
        }
        Ok(vec![
            SsoDomainVerified {
                domain: x.domain.clone(),
            }
            .into(),
        ])
    });

    sso.command(RemoveSsoDomain, |s, d, _, _| {
        if !s.domains.iter().any(|y| y.domain == d.domain) {
            return Err(rejected("No such domain", "not_found"));
        }
        Ok(vec![SsoDomainRemoved { domain: d.domain }.into()])
    });

    sso.command(EnforceSso, |s, d, _, _| {
        if s.status != SsoStatus::Active {
            return Err(rejected("Only an active SSO is enforced", "invalid_state"));
        }
        Ok(vec![
            SsoEnforcementChanged {
                enforced: d.enforced,
            }
            .into(),
        ])
    });

    sso.command(DisableSso, |s, _, _, _| {
        if s.status != SsoStatus::Active {
            return Err(rejected("Only an active SSO is disabled", "invalid_state"));
        }
        let mut events: Vec<NewEvent> = vec![];
        if s.enforced {
            events.push(SsoEnforcementChanged { enforced: false }.into());
        }
        events.push(SsoDisabled {}.into());
        Ok(events)
    });

    sso.command(EnableSso, |s, _, _, _| {
        if s.status != SsoStatus::Disabled {
            return Err(rejected("Only a disabled SSO is enabled", "invalid_state"));
        }
        Ok(vec![SsoEnabled {}.into()])
    });

    sso.command(DeleteSso, |s, _, _, _| {
        if matches!(s.status, SsoStatus::None | SsoStatus::Deleted) {
            return Err(rejected("No such SSO", "not_found"));
        }
        Ok(vec![SsoDeleted {}.into()])
    });
}
