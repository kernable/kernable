/** The account's own: the secret the API generated and showed (as a QR code). */
export class StartTotp extends Command {
  static personal: PersonalFields<StartTotp>[] = [{ fields: ["secret"], subject: (_d, id) => id }];
  secret!: string;
}

accountAggregate.command(StartTotp, (s, d) => {
  if (s.status !== "active") throw new Rejected("The account is not active", "invalid_state");
  if (s.totp?.confirmed) throw new Rejected("TOTP is on already", "exists");
  if (typeof d.secret !== "string" || !/^[A-Z2-7]{16,64}$/.test(d.secret)) throw new Rejected("A base32 secret", "invalid_secret");
  return [TotpStarted.new({ secret: d.secret })];
});

/** Recovery codes generated by the API, shown once: at least 8, each at least 10 characters. */
function recoveryHashes(codes: unknown): string[] {
  if (!Array.isArray(codes) || codes.length < 8 || !codes.every((c) => typeof c === "string" && c.length >= 10)) {
    throw new Rejected("At least 8 recovery codes of 10 characters", "invalid_recovery_codes");
  }
  return codes.map((c: string) => sha256(c));
}

/** The first code turns TOTP on, with recovery codes. */
export class ConfirmTotp extends Command {
  static secret: (keyof ConfirmTotp)[] = ["code", "recoveryCodes"];
  code!: string;
  recoveryCodes!: string[];
}

accountAggregate.command(ConfirmTotp, (s, d, _cmd, ctx) => {
  if (!s.totp?.secret || s.totp.confirmed) throw new Rejected("Start TOTP first", "invalid_state");
  const now = ctx.now().getTime();
  const step = totpStep(s.totp.secret, d.code, now);
  if (step === null) throw new Rejected("The code is not right", "wrong_code");
  return [TotpConfirmed.new({ step, at: now }), RecoveryCodesGenerated.new({ hashes: recoveryHashes(d.recoveryCodes) })];
});

/** A TOTP code or an unused recovery code: the proof both of the following take. */
function secondFactor(s: Account, code: unknown, now: number): { method: "totp" | "recovery"; step: number | null; recoveryCodeHash: string | null } | null {
  if (!s.totp?.confirmed || !s.totp.secret) return null;
  const step = totpStep(s.totp.secret, code, now);
  if (step !== null) return step > s.totp.lastStep ? { method: "totp", step, recoveryCodeHash: null } : null;
  const hash = typeof code === "string" ? sha256(code) : "";
  return s.recoveryCodes.includes(hash) ? { method: "recovery", step: null, recoveryCodeHash: hash } : null;
}

export class DisableTotp extends Command {
  static secret: (keyof DisableTotp)[] = ["code"];
  code!: string;
}

accountAggregate.command(DisableTotp, (s, d, _cmd, ctx) => {
  if (!secondFactor(s, d.code, ctx.now().getTime())) throw new Rejected("The code is not right", "wrong_code");
  return [TotpDisabled.new()];
});

