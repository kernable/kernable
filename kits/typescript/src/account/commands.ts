/**
 * Public: the refresh token is the proof. It names its session and generation; an older
 * generation is a reuse and ends the session.
 */
export class RefreshSession extends Command {
  static secret: (keyof RefreshSession)[] = ["refreshToken", "newRefreshToken", "ip"];
  refreshToken!: string;
  /** `<sessionId>.<generation + 1>.<secret>`, generated by the API. */
  newRefreshToken!: string;
  ip?: string;
}

sessionAggregate.command(RefreshSession, (s, d, cmd, ctx) => {
  const at = ctx.now().getTime();
  const parts = parseToken(d.refreshToken);
  const next = parseToken(d.newRefreshToken);
  if (s.status !== "active" || !parts || parts[0] !== cmd.aggregateId) throw new Rejected("Not a valid session", "invalid_token");
  const generation = Number(parts[1]);
  if (generation < s.generation) return [SessionEnded.new({ reason: "reuse" })];
  if (generation !== s.generation || sha256(d.refreshToken) !== s.refreshTokenHash) throw new Rejected("Not a valid session", "invalid_token");
  if (at > s.lastRefreshAt + SESSION_IDLE_DAYS * DAY) return [SessionEnded.new({ reason: "idle" })];
  if (at > s.openedAt + SESSION_MAX_DAYS * DAY) return [SessionEnded.new({ reason: "expired" })];
  if (!next || next[0] !== cmd.aggregateId || Number(next[1]) !== s.generation + 1) throw new Rejected("A malformed refresh token", "invalid_token");
  return [SessionRefreshed.new({
    generation: s.generation + 1, refreshTokenHash: sha256(d.newRefreshToken), ip: d.ip ?? null, accountId: s.accountId!, factors: s.factors, at,
  })];
});

export class RegisterAccount extends Command {
  static personal: PersonalFields<RegisterAccount>[] = [{ fields: ["email", "name"], subject: (_d, id) => id }];
  static secret: (keyof RegisterAccount)[] = ["password"];
  email!: string;
  name!: string;
  password?: string;
  /** Set by the API when an accepted invitation proved the email: active at once. */
  verified?: boolean;
}

/** A new verification token, kept in the vault under its own subject until used. */
export function verificationRequested(email: string, at: number): VerificationRequested {
  return VerificationRequested.new({ tokenId: randomSecret(9), token: randomSecret(), email, expiresAt: at + VERIFICATION_HOURS * HOUR });
}

accountAggregate.command(RegisterAccount, async (s, d, _cmd, ctx) => {
  const at = ctx.now().getTime();
  // A registration whose verification expired unverified is taken over by a new one of the same
  // address, so nobody blocks someone else's address (design/kits.md).
  const expired = s.status === "pending" && !s.openTokens.some((t) => t.purpose === "verify" && t.expiresAt > at);
  if (s.status !== "none" && !expired) throw new Rejected("The account exists", "exists");
  const email = normalEmail(d.email);
  if (expired && email !== s.email) throw new Rejected("Only the same address takes over a registration", "exists");
  if (!validEmail(email)) throw new Rejected("Not an email address", "invalid_email");
  if (typeof d.name !== "string" || !d.name.trim() || d.name.length > 200) throw new Rejected("A name is needed", "invalid_name");
  if (d.password !== undefined && !validPassword(d.password)) throw new Rejected("A password has 10 to 1024 characters", "weak_password");
  const passwordHash = d.password === undefined ? null : await hashPassword(d.password);
  const verified = d.verified === true;
  const registered = AccountRegistered.new({ email, name: d.name.trim(), passwordHash, verified, at });
  return verified ? [registered] : [registered, verificationRequested(email, at)];
});

export class RequestVerification extends Command {}

accountAggregate.command(RequestVerification, (s, _d, _cmd, ctx) => {
  if (s.status !== "pending") throw new Rejected("Only a pending account is verified", "invalid_state");
  return [verificationRequested(s.email!, ctx.now().getTime())];
});

/**
 * Public: the password is the proof. The IP and user agent stay with the events (personal); the
 * command keeps them, like the password, only until it completes.
 */
export class SignIn extends Command {
  static secret: (keyof SignIn)[] = ["password", "refreshToken", "ip", "userAgent"];
  sessionId!: string;
  password!: string;
  /** `<sessionId>.1.<secret>`, generated by the API; the account keeps its hash only. */
  refreshToken!: string;
  ip?: string;
  userAgent?: string;
}

// A failed attempt is an event, not a rejection. A reactor opens the session.
accountAggregate.command(SignIn, async (s, d, _cmd, ctx) => {
  const at = ctx.now().getTime();
  const failed = (reason: SignInFailed["reason"]) => [SignInFailed.new({ method: "password", reason, ip: d.ip ?? null, at })];
  if (s.status === "none" || s.status === "deleted") throw new Rejected("No such account", "not_found");
  const refresh = parseToken(d.refreshToken);
  if (!refresh || refresh[0] !== d.sessionId || refresh[1] !== "1") throw new Rejected("A malformed refresh token", "invalid_token");
  if (at < lockedUntil(s)) return failed("locked");
  if (!(await checkPassword(s.password?.hash, d.password))) return failed("wrong_password");
  if (s.status === "pending") return failed("not_verified");
  if (s.status !== "active") return failed("not_active");
  return [SignedIn.new({
    sessionId: d.sessionId, method: "password", factors: ["password"], refreshTokenHash: sha256(d.refreshToken),
    ip: d.ip ?? null, userAgent: d.userAgent ?? null, mfa: s.totp?.confirmed === true, at,
  })];
});

/** Public: the token from the mail is the proof. */
export class VerifyEmail extends Command {
  static secret: (keyof VerifyEmail)[] = ["token"];
  token!: string;
}

accountAggregate.command(VerifyEmail, (s, d, cmd, ctx) => {
  const parts = parseToken(d.token);
  const open = s.openTokens.find((t) => t.purpose === "verify" && parts && t.tokenId === parts[1]);
  if (!parts || parts[0] !== cmd.aggregateId || !open?.token || !equalSecrets(open.token, parts[2])) {
    throw new Rejected("The link is not valid", "invalid_token");
  }
  if (ctx.now().getTime() > open.expiresAt) throw new Rejected("The link has expired", "expired_token");
  return [EmailVerified.new({ tokenId: open.tokenId })];
});

