// Generates docs/reference/*.md from the code, so the reference cannot drift from it:
// the kernable start flags from crates/kernable-kernel/src/config.rs, the CLI from its usage text, the
// protocol from proto/kernable/v1/kernable.proto, metrics from metrics.rs, and the SDK APIs
// from the TypeScript sources (TSDoc), the Python sources (docstrings) and the Rust sources
// (doc comments).
//
// node scripts/reference.ts          writes the files
// node scripts/reference.ts --check  fails if a file is out of date, or if a rejection code
//                                    in the sources is missing from reference/errors.md

import { readFileSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { join } from "node:path";
import ts from "typescript";

const ROOT = new URL("../../", import.meta.url).pathname;
const read = (path: string) => readFileSync(join(ROOT, path), "utf8");
const HEADER = "<!-- Generated by docs/scripts/reference.ts from the sources; do not edit. -->\n\n";
const cell = (s: string) => s.replace(/\|/g, "\\|").replace(/\n+/g, " ").trim();

// ---- kernable start ----

function rustString(s: string): string {
  return s.replace(/\\"/g, '"').replace(/\\\\/g, "\\");
}

function configReference(): string {
  const src = read("crates/kernable-kernel/src/config.rs");
  const body = src.slice(src.indexOf("pub const FLAGS"), src.indexOf("];", src.indexOf("pub const FLAGS")));
  const str = /"((?:[^"\\]|\\.)*)"/.source;
  const re = new RegExp(`\\(\\s*${str},\\s*${str},\\s*${str},\\s*${str},?\\s*\\)`, "g");
  const rows = [...body.matchAll(re)].map(([, flag, variable, def, doc]) => {
    const value = flag === "--root" ? "**required**" : def ? `\`${def}\`` : "—";
    return `| \`${flag}\` | \`${variable}\` | ${value} | ${cell(rustString(doc))} |`;
  });
  return `${HEADER}# kernable start

The kernel takes its settings as flags of \`kernable start\`. Every flag has an environment variable; a flag wins over its variable, and the variable over the default. A flag is written \`--flag value\` or \`--flag=value\`. Relative paths resolve against the working directory. \`kernable start --help\` lists the flags.

\`\`\`sh
kernable start --root root.pub --store sqlite:kernable.db --listen 127.0.0.1:7233
\`\`\`

The kernel holds no keys of services and no permissions: it trusts the root keys, and a root key says with a grant what each key may do (see [Trust](../concepts/trust) and [Manage keys](../how-to/keys)). SIGHUP reads the kernel key file again; every other change needs a restart.

| Flag | Variable | Default | Description |
|---|---|---|---|
${rows.join("\n")}
`;
}

// ---- CLI ----

function cliReference(): string {
  const usage = read("crates/kernable-kernel/src/main.rs").match(/const USAGE: &str = "([\s\S]*?)";/)![1].replace(/\\\n\s*/g, "");
  return `${HEADER}# kernable (CLI)

The \`kernable\` command runs the kernel, creates keys, grants and certificates, revokes keys, checks and migrates stores, and submits commands for scripting.

\`\`\`text
${usage}
\`\`\`
`;
}

// ---- protocol ----

function protoReference(): string {
  const lines = read("proto/kernable/v1/kernable.proto").split("\n");
  const out: string[] = [];
  let comment: string[] = [];
  let block: { kind: string; name: string; doc: string; rows: string[] } | undefined;
  let depth = 0;
  const flush = () => {
    if (!block) return;
    out.push(`### ${block.name}`, "", block.doc ? `${block.doc}\n` : "");
    if (block.rows.length) {
      const head = block.kind === "service" ? "| RPC | Request | Response | Description |\n|---|---|---|---|" : block.kind === "enum" ? "| Value | Number | Description |\n|---|---|---|" : "| Field | Type | Number | Description |\n|---|---|---|---|";
      out.push(head, ...block.rows, "");
    }
    block = undefined;
  };
  const header = lines.slice(0, lines.findIndex((l) => l.startsWith("syntax"))).map((l) => l.replace(/^\/\/ ?/, "")).join("\n");
  for (const raw of lines) {
    const line = raw.trim();
    if (line.startsWith("// ----")) {
      comment = [];
      continue;
    }
    if (line.startsWith("//")) {
      comment.push(line.replace(/^\/\/ ?/, ""));
      continue;
    }
    const open = line.match(/^(message|service|enum) (\w+) \{/);
    if (open && depth === 0) {
      flush();
      block = { kind: open[1], name: open[2], doc: comment.join(" "), rows: [] };
      depth = 1;
      comment = [];
      continue;
    }
    if (line.startsWith("oneof ") || /^(message|enum) /.test(line)) {
      depth++;
      comment = [];
      continue;
    }
    if (line === "}") {
      depth--;
      if (depth === 0) flush();
      comment = [];
      continue;
    }
    if (block) {
      const trailing = line.match(/\/\/ ?(.*)$/)?.[1] ?? "";
      const doc = cell([...comment, trailing].filter(Boolean).join(" "));
      const rpc = line.match(/^rpc (\w+)\((stream )?(\w+)\) returns \((stream )?(\w+)\)/);
      const field = line.match(/^(repeated |optional )?([\w.]+) (\w+) = (\d+);/);
      const value = line.match(/^(\w+) = (\d+);/);
      if (rpc) block.rows.push(`| \`${rpc[1]}\` | ${rpc[2] ?? ""}\`${rpc[3]}\` | ${rpc[4] ?? ""}\`${rpc[5]}\` | ${doc} |`);
      else if (field) block.rows.push(`| \`${field[3]}\` | ${(field[1] ?? "").trim()} \`${field[2]}\` | ${field[4]} | ${doc} |`);
      else if (value) block.rows.push(`| \`${value[1]}\` | ${value[2]} | ${doc} |`);
      comment = [];
    } else if (line === "") {
      comment = [];
    }
  }
  flush();
  return `${HEADER}# Protocol

gRPC over a Unix socket or TCP (with mutual TLS), package \`kernable.v1\`, from \`proto/kernable/v1/kernable.proto\`. Signed fields and their byte layouts are in [Signatures](./signing).

${header}

${out.join("\n")}`;
}

// ---- metrics ----

function metricsReference(): string {
  const src = read("crates/kernable-kernel/src/metrics.rs");
  const rows: string[] = [];
  const re = /"(kernable_[a-z_]+)",\s*(?:"(counter|gauge)",\s*)?"([^"]+)"/g;
  const found = [...src.matchAll(re)];
  found.forEach((m, i) => {
    // Up to the next metric, without helper definitions in between (`let label = ...`).
    const segment = src.slice(m.index, found[i + 1]?.index ?? src.length).split("\n").filter((l) => !l.includes("let ")).join("\n");
    const labels = [...new Set([...segment.matchAll(/\{(\w+)=\\"/g)].map((l) => l[1]))];
    if (/_lag|_position"|_connected/.test(m[0]) && m[1].startsWith("kernable_listener")) labels.push("listener");
    const kind = m[2] ?? (m[1].endsWith("_seconds") ? "summary" : "gauge");
    rows.push(`| \`${m[1]}\` | ${kind} | ${labels.map((l) => `\`${l}\``).join(", ")} | ${cell(m[3])} |`);
  });
  return `${HEADER}# Metrics and health

With \`--metrics-listen 127.0.0.1:9233\` the kernel serves, on that address:

- \`GET /metrics\`: Prometheus text format, below.
- \`GET /health\`: 200 while the process runs.
- \`GET /ready\`: 200 once every registered listener is connected and has caught up, else 503 naming the listeners it waits for.

| Metric | Type | Labels | Description |
|---|---|---|---|
${rows.join("\n")}
`;
}

// ---- TypeScript SDK ----

function tsReference(): string {
  const files = ["sdks/typescript/src/index.ts", "sdks/typescript/src/store.ts"].map((f) => join(ROOT, f));
  const program = ts.createProgram(files, { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.NodeNext, allowImportingTsExtensions: true, noEmit: true });
  const checker = program.getTypeChecker();
  const doc = (node: ts.Node) => ts.getJSDocCommentsAndTags(node).filter(ts.isJSDoc).map((d) => ts.getTextOfJSDocComment(d.comment) ?? "").join("\n").trim();
  const exported = (node: ts.Node) => ts.canHaveModifiers(node) && ts.getModifiers(node)?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword);
  const isPublic = (node: ts.Node) => !(ts.canHaveModifiers(node) && ts.getModifiers(node)?.some((m) => m.kind === ts.SyntaxKind.PrivateKeyword || m.kind === ts.SyntaxKind.ProtectedKeyword));
  // The declaration up to its body, on one line.
  const sig = (node: ts.Node, source: ts.SourceFile) => {
    const body = (node as { body?: ts.Node }).body;
    const text = source.text.slice(node.getStart(source), body ? body.getStart(source) : node.getEnd());
    return text.replace(/\s+/g, " ").replace(/\(\s/g, "(").replace(/,\s\)/g, ")").replace(/[;{\s]+$/, "").trim();
  };
  const sections: string[] = [];
  for (const file of files) {
    const source = program.getSourceFile(file)!;
    ts.forEachChild(source, (node) => {
      if (!exported(node)) return;
      if (ts.isClassDeclaration(node) || ts.isInterfaceDeclaration(node)) {
        const name = node.name!.text;
        const members: string[] = [];
        for (const m of node.members) {
          if (!isPublic(m) || !m.name || (ts.isIdentifier(m.name) && m.name.text.startsWith("_"))) continue;
          const d = doc(m);
          if (/@internal/.test(m.getFullText(source))) continue;
          if (ts.isConstructorDeclaration(m)) continue;
          const text = sig(m, source).replace(/;$/, "");
          members.push(`- \`${text}\`${d ? `: ${cell(d)}` : ""}`);
        }
        sections.push(`### ${name}\n\n${doc(node)}\n\n${members.join("\n")}\n`);
      } else if (ts.isFunctionDeclaration(node) && node.name) {
        sections.push(`### ${node.name.text}()\n\n\`${sig(node, source)}\`\n\n${doc(node)}\n`);
      } else if (ts.isTypeAliasDeclaration(node)) {
        sections.push(`### ${node.name.text}\n\n\`\`\`ts\n${node.getText(source)}\n\`\`\`\n\n${doc(node)}\n`);
      }
    });
  }
  void checker;
  return `${HEADER}# TypeScript SDK

\`npm install @kernable/sdk\` (Node ≥ 22.18). Generated from the TSDoc in \`sdks/typescript/src\`.

${sections.join("\n")}`;
}

