// ---- Rust SDK ----

/**
 * The public items of the Rust SDK with their doc comments: structs and enums with their public
 * fields and variants, the public methods of their `impl` blocks, traits and free functions.
 * A line-based reading of rustfmt-formatted sources, enough for this crate.
 */
function rustReference(): string {
  const files = ["lib.rs", "domain.rs", "worker.rs", "listener.rs", "store.rs", "data.rs", "context.rs", "error.rs"];
  const sections = new Map<string, { head: string; doc: string; members: string[] }>();
  const section = (name: string, head = "", doc = "") => {
    const s = sections.get(name) ?? { head: "", doc: "", members: [] };
    if (head) s.head = head;
    if (doc) s.doc = doc;
    sections.set(name, s);
    return s;
  };
  // Doc comments as text: rustdoc links as code, a `# Panics` section as "Panics if …".
  const text = (lines: string[]) =>
    lines
      .join("\n")
      .replace(/^# Panics\n\n?If /gm, "Panics if ")
      .replace(/\[(`[^`]+`)\](\([^)]*\))?/g, "$1")
      .trim();
  // A declaration up to its body, on one line.
  const declaration = (lines: string[], i: number) => {
    let sig = "";
    for (let j = i; j < lines.length; j++) {
      sig += ` ${lines[j].trim()}`;
      if (/[{;]$/.test(lines[j].trim())) break;
    }
    return sig
      .replace(/\s+/g, " ")
      .replace(/\(\s/g, "(")
      .replace(/,\s?\)/g, ")")
      .replace(/,\s?>/g, ">")
      .replace(/\s*[{;]$/, "")
      .replace(/,$/, "")
      .trim()
      .replace(/^pub /, "")
      .replace(/\bmut self\b/, "self");
  };
  for (const file of files) {
    const lines = read(`sdks/rust/src/${file}`).split("\n");
    let doc: string[] = [];
    let impl: string | undefined;
    let item: { name: string; indent: number } | undefined;
    for (let i = 0; i < lines.length; i++) {
      const line = lines[i];
      const trimmed = line.trim();
      const indent = line.length - line.trimStart().length;
      if (trimmed.startsWith("///")) {
        doc.push(trimmed.replace(/^\/\/\/ ?/, ""));
        continue;
      }
      if (trimmed.startsWith("#[") || trimmed === "") {
        if (trimmed === "") doc = [];
        continue;
      }
      if (indent === 0) {
        impl = undefined;
        item = undefined;
        const m = trimmed.match(/^pub (struct|enum|trait|type|fn) (\w+)/);
        if (m) {
          const [, kind, name] = m;
          if (kind === "fn") {
            section(`${name}()`, `\`${declaration(lines, i)}\``, text(doc));
          } else if (kind === "type") {
            section(name, `\`${declaration(lines, i)}\``, text(doc));
          } else {
            section(name, "", text(doc));
            if (trimmed.endsWith("{")) item = { name, indent };
          }
        }
        const im = trimmed.match(/^impl(?:<[^>]*>)? (\w+)(?:<[^>]*>)? \{$/);
        if (im && sections.has(im[1])) impl = im[1];
      } else if (item && indent === 4) {
        const field = trimmed.match(/^pub (\w+): (.+),$/);
        const variant = trimmed.match(/^([A-Z]\w*)(\(.*\))?,$/);
        if (field) section(item.name).members.push(`- \`${field[1]}: ${field[2]}\`${doc.length ? `: ${cell(text(doc))}` : ""}`);
        else if (variant) section(item.name).members.push(`- \`${variant[1]}${variant[2] ?? ""}\`${doc.length ? `: ${cell(text(doc))}` : ""}`);
      } else if (impl && indent === 4 && /^pub (async )?fn /.test(trimmed)) {
        section(impl).members.push(`- \`${declaration(lines, i)}\`${doc.length ? `: ${cell(text(doc))}` : ""}`);
      }
      doc = [];
    }
  }
  const body = [...sections].map(([name, s]) => `### ${name}\n\n${[s.head, s.doc, s.members.join("\n")].filter(Boolean).join("\n\n")}\n`);
  return `${HEADER}# Rust SDK

\`cargo add kernable\` (async, on tokio). Generated from the doc comments in \`sdks/rust/src\`.

${body.join("\n")}`;
}

// ---- errors: hand-written, checked for completeness ----

function errorCodes(): string[] {
  const sources = [
    "crates/kernable-kernel/src/lib.rs",
    "crates/kernable-kernel/src/listeners.rs",
    "sdks/typescript/src/index.ts",
    "sdks/python/kernable/__init__.py",
    "sdks/rust/src/domain.rs",
    "sdks/rust/src/listener.rs",
    "sdks/rust/src/worker.rs",
  ].map(read).join("\n");
  const codes = [
    ...sources.matchAll(/code: "([a-z_]+)"/g),
    ...sources.matchAll(/refused\(\s*"([a-z_]+)"/g),
    ...sources.matchAll(/Rejected\([^)]*?, "([a-z_]+)"\)/g),
    ...sources.matchAll(/pb\.Rejected\(code="([a-z_]+)"/g),
    ...sources.matchAll(/\.code\("([a-z_]+)"\)/g),
    ...sources.matchAll(/const SNAPSHOT_STALE: &str = "([a-z_]+)"/g),
  ].map((m) => m[1]);
  return [...new Set(codes)].sort();
}

const generated: Record<string, () => string> = {
  "reference/configuration.md": configReference,
  "reference/cli.md": cliReference,
  "reference/protocol.md": protoReference,
  "reference/metrics.md": metricsReference,
  "reference/sdk-typescript.md": tsReference,
  "reference/sdk-python.md": pyReference,
  "reference/sdk-rust.md": rustReference,
};

const check = process.argv.includes("--check");
const stale: string[] = [];
for (const [path, make] of Object.entries(generated)) {
  const file = join(ROOT, "docs", path);
  const content = make();
  if (check) {
    let current = "";
    try {
      current = readFileSync(file, "utf8");
    } catch {}
    if (current !== content) stale.push(path);
  } else {
    writeFileSync(file, content);
  }
}
// Every metric named anywhere in the docs must exist.
const metrics = new Set([...metricsReference().matchAll(/`(kernable_[a-z_]+)`/g)].map((m) => m[1]));
const unknownMetrics: string[] = [];
for (const file of execFileSync("git", ["ls-files", "docs/*.md", "docs/**/*.md"], { cwd: ROOT, encoding: "utf8" }).split("\n").filter(Boolean)) {
  for (const m of readFileSync(join(ROOT, file), "utf8").matchAll(/\b(kernable_[a-z_]+)/g)) {
    const name = m[1].replace(/_(sum|count)$/, "");
    if (!metrics.has(name)) unknownMetrics.push(`${m[1]} (${file})`);
  }
}
const errors = readFileSync(join(ROOT, "docs/reference/errors.md"), "utf8");
const undocumented = errorCodes().filter((c) => !errors.includes(`\`${c}\``));
if (unknownMetrics.length) {
  console.error(`unknown metrics in the docs: ${unknownMetrics.join(", ")}`);
  process.exit(1);
}
if (stale.length || undocumented.length) {
  if (stale.length) console.error(`out of date (run npm run reference in docs/): ${stale.join(", ")}`);
  if (undocumented.length) console.error(`rejection codes missing from reference/errors.md: ${undocumented.join(", ")}`);
  if (check || undocumented.length) process.exit(1);
}
