// Wraps the parts of a usage description that are code: placeholders, flags, file names,
// store URLs, codes and variables.
function codeify(text: string): string {
  const code = (t: string) =>
    /[<*]/.test(t) ||
    /^--?[a-z]/.test(t) ||
    /^KERNABLE_/.test(t) ||
    /^[\w.-]*\.(key|pub|grant|crt|db|json)$/.test(t) ||
    /^(sqlite|file|memory|unix|https?):/.test(t) ||
    /^(https?:\/\/)?host:port$/.test(t) ||
    /^[\w.]+=/.test(t) ||
    /^\d{4}-\d\d-\d\dT/.test(t) ||
    /^[\d.]+:\d+$/.test(t) ||
    /^[A-Z]+_[A-Z_]+$/.test(t) ||
    /^(OK|PROBLEM|SUSPECT|TAMPERED)$/.test(t) ||
    /^[a-z]+_[a-z_]+$/.test(t);
  return text
    .replace(/kernable [a-z]+ --help/g, (m) => `\`${m}\``)
    .replace(/Actions: ([a-z_ ]+)\./, (_, list: string) => `Actions: ${list.split(" ").map((a) => `\`${a}\``).join(" ")}.`)
    .split(" ")
    .map((token) => {
      if (token.includes("`")) return token;
      if (/^(sqlite|file|memory|unix):$/.test(token)) return `\`${token}\``;
      const [, pre, core, post] = token.match(/^(\(?)(.*?)([.,;:)]*)$/)!;
      return core && code(core) ? `${pre}\`${core}\`${post}` : token;
    })
    .join(" ")
    .replace(/`(--[a-z-]+)` `([^`]+)`/g, "`$1 $2`"); // a flag with its value
}

function cliReference(): string {
  const usage = read("crates/kernable-kernel/src/main.rs").match(/const USAGE: &str = "([\s\S]*?)";/)![1].replace(/\\\n\s*/g, "");
  // The usage text: group headings ("Keys and trust:"), commands ("  kernable ..."), each
  // with its description, on the same line after two spaces or on the indented lines below.
  type Command = { sigs: string[]; doc: string[] };
  const groups: { title: string; text: string[]; commands: Command[] }[] = [];
  for (const line of usage.split("\n").slice(1)) {
    if (!line.trim()) continue;
    if (/^\S.*:$/.test(line)) {
      groups.push({ title: line.slice(0, -1), text: [], commands: [] });
      continue;
    }
    const group = groups.at(-1)!;
    const command = group.commands.at(-1);
    if (line.startsWith("  kernable ")) {
      const [sig, doc] = line.trim().split(/\s{2,}/);
      if (command && !command.doc.length) command.sigs.push(sig);
      else group.commands.push({ sigs: [sig], doc: [] });
      if (doc) group.commands.at(-1)!.doc.push(doc);
    } else if (command) command.doc.push(line.trim());
    else group.text.push(line.trim());
  }
  const sections = groups.map(({ title, text, commands }) => {
    const parts = [`## ${title}`, ""];
    if (text.length) parts.push(codeify(text.join(" ")), "");
    for (const c of commands) {
      const name = c.sigs[0].split(" ").filter((_, i, words) => !words.slice(0, i + 1).some((w) => /^[<[-]/.test(w))).join(" ");
      parts.push(`### \`${name}\``, "", "```text", ...c.sigs, "```", "", codeify(c.doc.join(" ")), "");
    }
    return parts.join("\n");
  });
  return `${HEADER}# kernable (CLI)

The \`kernable\` command runs the kernel and does everything around it: it creates keys, grants and development certificates, revokes keys, applies a service's membership, lists what is registered, checks stores, and submits single commands for scripting. \`kernable\` without arguments prints this page as text. The flags of \`kernable start\` are in [kernable start](./configuration).

Commands that take an \`<addr>\` talk to a running kernel. Commands that take a \`<store>\` open the store file directly: the ones that only read it work while the kernel runs, the ones that change it need the kernel stopped.

${sections.join("\n")}`;
}

